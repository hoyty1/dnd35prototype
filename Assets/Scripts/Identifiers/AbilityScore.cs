namespace DND35e.Identifiers
{
    /// <summary>
    /// Type-safe enumeration for the six D&D ability scores.
    /// Replaces string-based GameConstants.ABILITY_* with compiler-enforced types.
    /// </summary>
    public enum AbilityScore
    {
        Strength = 0,
        Dexterity = 1,
        Constitution = 2,
        Intelligence = 3,
        Wisdom = 4,
        Charisma = 5
    }
}
